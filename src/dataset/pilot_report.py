"""Build results/generation/pilot_report.md from the pilot artefacts.

Computes every quantitative part of the gate report: per-generator validation
pass-rates and failure breakdowns, worked examples with their labels, observed
cost per record, and the extrapolated full-run cost from config.full_run.

The Sinhala-fluency assessment is a human judgement and is written into
`results/generation/fluency_assessment.md`; if that file exists it is spliced in, so
re-running this script never overwrites the qualitative section.
"""
from __future__ import annotations

import argparse
import sys
from collections import Counter, defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from generate import OUT_FILES  # noqa: E402
from utils import force_utf8_stdout, load_config, read_jsonl  # noqa: E402


def _pct(a: int, b: int) -> str:
    return f"{a/b:.1%}" if b else "n/a"


def collect(cfg: dict) -> dict:
    gdir = Path(cfg["paths"]["generated_dir"])
    ldir = Path(cfg["paths"]["logs_dir"])

    records: list[dict] = []
    for fname in OUT_FILES.values():
        records.extend(read_jsonl(gdir / fname))

    rejected = list(read_jsonl(ldir / "rejected.jsonl"))
    costs = list(read_jsonl(ldir / "cost.jsonl"))
    return {"records": records, "rejected": rejected, "costs": costs}


def build(cfg: dict) -> str:
    data = collect(cfg)
    records, rejected, costs = data["records"], data["rejected"], data["costs"]
    gens = list(cfg["generators"].keys())

    L: list[str] = []
    L.append("# Pilot report — Sinhala human–AI boundary detection")
    L.append("")
    L.append("Generated by `src/dataset/pilot_report.py`. This is the mandatory gate "
             "before bulk generation.")
    L.append("")

    # ---------------------------------------------------------- headline --
    total_cost = sum(c.get("cost_usd", 0) for c in costs)
    L.append("## Headline")
    L.append("")
    L.append(f"- Documents accepted: **{len(records)}**")
    L.append(f"- API calls: **{len(costs)}**")
    L.append(f"- Pilot spend: **${total_cost:.4f}**")
    L.append("")

    # ------------------------------------------------- per-generator rates --
    L.append("## Validation pass-rate by generator")
    L.append("")
    L.append("A *document* is accepted only if every AI span in it validated "
             "within 3 attempts. A *call* is one model request.")
    L.append("")
    L.append("| generator | role | docs accepted | calls | rejected calls | "
             "call pass-rate | spend |")
    L.append("|---|---|---|---|---|---|---|")

    per_gen_cost: dict[str, float] = defaultdict(float)
    per_gen_calls: Counter = Counter()
    for c in costs:
        per_gen_cost[c["generator"]] += c.get("cost_usd", 0)
        per_gen_calls[c["generator"]] += 1
    per_gen_rej: Counter = Counter(r.get("generator") for r in rejected)
    per_gen_docs: Counter = Counter(r["generator"] for r in records)

    for g in gens:
        calls = per_gen_calls.get(g, 0)
        rej = per_gen_rej.get(g, 0)
        ok = calls - rej
        L.append(f"| {g} | {cfg['generators'][g]['role']} | "
                 f"{per_gen_docs.get(g,0)} | {calls} | {rej} | "
                 f"{_pct(ok, calls)} | ${per_gen_cost.get(g,0):.4f} |")
    L.append("")

    # ------------------------------------------------- failure breakdown ---
    L.append("### Rejection reasons")
    L.append("")
    reasons: dict = defaultdict(Counter)
    for r in rejected:
        for e in r.get("errors", []):
            reasons[r.get("generator")][e.split(":")[0]] += 1
    kinds = sorted({k for c in reasons.values() for k in c})
    if kinds:
        L.append("| generator | " + " | ".join(kinds) + " |")
        L.append("|---|" + "---|" * len(kinds))
        for g in gens:
            row = [str(reasons[g].get(k, 0)) for k in kinds]
            L.append(f"| {g} | " + " | ".join(row) + " |")
    else:
        L.append("_No rejections recorded._")
    L.append("")

    # ------------------------------------------------- by construction -----
    L.append("## Accepted documents by construction type")
    L.append("")
    types = list(OUT_FILES.keys())
    L.append("| generator | " + " | ".join(types) + " | total |")
    L.append("|---|" + "---|" * (len(types) + 1))
    cube: dict = defaultdict(Counter)
    for r in records:
        cube[r["generator"]][r["construction_type"]] += 1
    for g in gens:
        row = [str(cube[g].get(t, 0)) for t in types]
        L.append(f"| {g} | " + " | ".join(row) + f" | {sum(cube[g].values())} |")
    L.append("")

    # ------------------------------------------------------- cost model ----
    L.append("## Full-run cost estimate")
    L.append("")
    L.append("Extrapolated from observed cost per accepted document in this "
             "pilot, so it already includes the cost of retries and of "
             "documents that were rejected and skipped.")
    L.append("")
    L.append("| generator | $/accepted doc | target docs | projected |")
    L.append("|---|---|---|---|")
    grand = 0.0
    targets = cfg["full_run"]["docs_per_generator"]
    for g in gens:
        docs = per_gen_docs.get(g, 0)
        per_doc = (per_gen_cost.get(g, 0) / docs) if docs else 0.0
        tgt = targets.get(g, 0)
        proj = per_doc * tgt
        grand += proj
        per_doc_s = f"${per_doc:.4f}" if docs else "n/a"
        L.append(f"| {g} | {per_doc_s} | {tgt} | ${proj:.2f} |")
    L.append(f"| **total** | | | **${grand:.2f}** |")
    L.append("")

    # --------------------------------------------------------- examples ----
    L.append("## Example generations")
    L.append("")
    L.append("`H` = human sentence (label 0), `AI` = generated sentence "
             "(label 1). Boundaries are the label-change indices.")
    L.append("")
    for g in gens:
        sel = [r for r in records if r["generator"] == g]
        if not sel:
            L.append(f"### {g}")
            L.append("")
            L.append("_No accepted documents._")
            L.append("")
            continue
        # Spread examples across construction types.
        by_type: dict = defaultdict(list)
        for r in sel:
            by_type[r["construction_type"]].append(r)
        picked: list[dict] = []
        while len(picked) < 5 and any(by_type.values()):
            for t in types:
                if by_type[t] and len(picked) < 5:
                    picked.append(by_type[t].pop(0))

        L.append(f"### {g}")
        L.append("")
        for i, r in enumerate(picked, 1):
            L.append(f"**Example {i}** — `{r['construction_type']}`, "
                     f"split=`{r['split']}`, source=`{r['source_id']}` "
                     f"(*{r['title']}*)")
            L.append("")
            L.append(f"- labels: `{r['labels']}`")
            L.append(f"- boundaries: `{r['boundaries']}`  ·  "
                     f"normalised first boundary: "
                     f"`{r['boundary_position_normalized']:.3f}`"
                     if r.get("boundary_position_normalized") is not None
                     else f"- boundaries: `{r['boundaries']}`")
            L.append(f"- retries used: {r.get('retry_count', 0)}")
            L.append("")
            for idx, (s, lab) in enumerate(zip(r["sentences"], r["labels"])):
                tag = "**AI**" if lab else "H  "
                L.append(f"> `{idx:2d}` {tag} {s}")
            L.append("")
    L.append("")

    # --------------------------------------------- fluency (human-written) --
    L.append("## Sinhala fluency assessment")
    L.append("")
    frag = Path(cfg["paths"]["results_dir"]) / "generation" / "fluency_assessment.md"
    if frag.exists():
        L.append(frag.read_text(encoding="utf-8").strip())
    else:
        L.append("_Not yet written. Create `results/generation/fluency_assessment.md`; "
                 "its contents are spliced in here._")
    L.append("")
    return "\n".join(L)


def run(cfg: dict) -> None:
    force_utf8_stdout()
    rdir = Path(cfg["paths"]["results_dir"]) / "generation"
    rdir.mkdir(parents=True, exist_ok=True)
    out = rdir / "pilot_report.md"
    out.write_text(build(cfg), encoding="utf-8")
    print(f"wrote -> {out}")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", default="config.yaml")
    a = ap.parse_args()
    run(load_config(a.config))


if __name__ == "__main__":
    main()
